# Regenerate the reference pages of the manual from the package itself.
#
#   julia --project=. docs/generate_reference.jl
#
# Writes docs/src/reference/{schema,vocabulary,api}.md. Run after changing the
# schema, regenerating the vocabulary, or editing docstrings.

using BioNExt
using BioNExt: SCHEMA, INVERSES, SUBPROPERTIES, BN, BNR, ONTOLOGY_VERSION, Prop

const OUT = joinpath(@__DIR__, "src", "reference")
mkpath(OUT)
const HEADER = "<!-- AUTO-GENERATED by docs/generate_reference.jl — do not edit by hand. -->\n\n"

cell(s) = replace(string(s), "|" => "\\|", "\n" => " ")
docstring(x) = strip(string(Base.Docs.doc(x)))
first_paragraph(x) = (d = docstring(x); strip(split(replace(d, r"^\s*```.*?```\s*"s => ""), "\n\n")[1]))

julia_type(T, f) = replace(replace(string(fieldtype(T, f)), "BioNExt." => "", "Dates." => ""),
                            r"Union\{Nothing, (.*)\}" => s"Union{\1, Nothing}")

function range_text(p::Prop)
    p.kind === :ref ? join(("`" * class_name(T) * "`" for T in p.range), " \\| ") :
    p.kind === :term ? "term under `:$(p.range)`" :
    p.kind === :iri ? "external IRI / CURIE" : "`xsd:$(p.range)`"
end

# Chain of supertypes below Any, e.g. Gene -> [NodeEntity, Entity, Resource].
function supers(T)
    out = Type[]
    while (T = supertype(T)) !== Any
        push!(out, T)
    end
    return out
end

const INVERSE_OF = Dict(v => k for (k, v) in INVERSES)

const ORDER = [Taxon, Provenance, Gene, Dna, Rna, Protein, MolecularComplex, SmallMolecule,
               OrthologGroup, Interaction, Influence, Reaction, PathwayModule]

# --- schema.md -----------------------------------------------------------------
open(joinpath(OUT, "schema.md"), "w") do io
    print(io, HEADER)
    println(io, """
    # Schema reference

    Every concrete type, its fields, and the ontology property each field maps to.
    Ontology namespace: `bn:` = `$BN`, default resource namespace `bnr:` = `$BNR`
    (ontology version $ONTOLOGY_VERSION).

    **Kinds**
    - *ref*: the id of another resource in the graph, checked against the allowed classes
    - *term*: a controlled-vocabulary `Symbol` (see [Vocabulary](vocabulary.md))
    - *iri*: an external IRI or CURIE such as `"GO:0003700"`, which is not resolved in the graph
    - *literal*: a data value

    Fields typed `Vector` can hold many values; `Union{…, Nothing}` fields are optional
    single values. `id` (a `String`) is always the first field and is required.
    Edges also require `type`.
    """)
    for T in ORDER
        println(io, "## `", T, "` — `bn:", class_name(T), "`\n")
        println(io, first_paragraph(T), "\n")
        println(io, "Supertypes: ", join(("`$S`" for S in supers(T)), " → "), "\n")
        println(io, "| Field | Julia type | Property | Kind | Range |")
        println(io, "|---|---|---|---|---|")
        println(io, "| `id` | `String` | (subject IRI) | — | — |")
        for p in SCHEMA[T]
            prop = "`bn:$(p.pred)`"
            T === OrthologGroup && p.field === :members && (prop *= " / `bn:hasProteinMember`")
            haskey(INVERSE_OF, p.pred) && (prop *= " (inverse `bn:$(INVERSE_OF[p.pred])`)")
            println(io, "| `", p.field, "` | `", cell(julia_type(T, p.field)), "` | ", prop, " | ", p.kind, " | ", range_text(p), " |")
        end
        println(io)
    end
    println(io, """
    ## Derived (inverse) properties

    These ontology properties are not stored as fields. Each is the inverse of a field
    that is stored, so it can be queried, and it is written to RDF when `inverses = true`.

    | Ontology property | Derived from | Query |
    |---|---|---|""")
    queries = Dict("hasVariant" => "`variants(kg, x)`", "encodes" => "scan `Rna.encoded_by`",
                   "annotates" => "scan `Gene.templates`", "participatesInPathway" => "`pathways_of(kg, x)`",
                   "memberOfComplex" => "`complexes_of(kg, x)`", "hasOrthologGroup" => "`ortholog_groups_of(kg, x)`")
    for (inv, canon) in sort!(collect(INVERSES))
        println(io, "| `bn:$inv` | `bn:$canon` | ", queries[inv], " |")
    end
    println(io, "| `bn:participatesInEdge` | `bn:hasLeft` / `bn:hasRight` of edges | `edges_of(kg, x)` |")
end

# --- vocabulary.md -------------------------------------------------------------
open(joinpath(OUT, "vocabulary.md"), "w") do io
    print(io, HEADER)
    println(io, """
    # Controlled vocabulary

    All $(length(VOCABULARY)) terms of ontology version $ONTOLOGY_VERSION. Use them as `Symbol`s,
    e.g. `type = :Binding` or `cellular_location = [:Nucleus]`. A term is accepted wherever
    its ancestor is expected, so `:NegativeCorrelation` is a valid `:RelationshipType`.
    """)
    depth(t) = (d = 0; p = term(t).parent; while p !== nothing && p !== :ControlledVocabulary; d += 1; p = term(p).parent; end; d)
    tree(root) = sort(terms(root); by = t -> (depth(t), string(t)))
    plist(v) = isempty(v) ? "any" : join(("`$x`" for x in v), ", ")
    links(t) = join(("[$(last(split(u, '/')))]($u)" for u in term(t).see_also), " ")

    println(io, "## Hierarchy\n\n```")
    function show_tree(t, indent)
        println(io, "  "^indent, t, isempty(term(t).label) ? "" : "  — " * term(t).label)
        foreach(c -> show_tree(c, indent + 1), sort([k for (k, v) in VOCABULARY if v.parent === t]))
    end
    show_tree(:ControlledVocabulary, 0)
    println(io, "```\n")

    println(io, "## Relationship types (`:RelationshipType`)\n")
    println(io, "Used in the `type` field of `Interaction`, `Influence` and `Reaction`. `validate` checks the",
            " participants against **Expected left / right** (from `bn:expectedLeft` / `bn:expectedRight`);",
            " \"any\" means the ontology does not restrict them.\n")
    println(io, "| Term | Label | Expected left | Expected right | Definition | See also |")
    println(io, "|---|---|---|---|---|---|")
    for t in tree(:RelationshipType)
        x = term(t)
        println(io, "| `:", t, "` | ", cell(x.label), " | ", plist(x.expected_left), " | ", plist(x.expected_right),
                " | ", cell(x.comment), " | ", links(t), " |")
    end
    for (root, title, use) in ((:CellularLocation, "Cellular locations", "the `cellular_location` field of node entities"),
                               (:DnaRegion, "DNA region types", "the `regions` field of `Dna` and `Gene`"),
                               (:RnaRegion, "RNA region types", "the `regions` field of `Rna`"))
        println(io, "\n## $title (`:$root`)\n\nUsed in $use.\n")
        println(io, "| Term | Label | Definition | See also |\n|---|---|---|---|")
        for t in tree(root)
            println(io, "| `:", t, "` | ", cell(term(t).label), " | ", cell(term(t).comment), " | ", links(t), " |")
        end
    end
end

# --- api.md --------------------------------------------------------------------
const GROUPS = [
    "Graph container" => [:KnowledgeGraph, :add!, :resources, :nodes, :edges, :pathways, :references, :referrers],
    "Queries" => [:edges_of, :neighbors, :pathways_of, :components, :complexes_of, :variants, :ortholog_groups_of],
    "Indexing" => [:index!, :reindex!, :unindex!, :isindexed],
    "Graph algorithms" => [:degree_of, :shortest_path, :network_components, :subgraph, :to_graph],
    "Entity resolution" => [:duplicates, :resolve!, :integrate!, :find_entity, :identifier_map,
                            :normalize_identifier, :Resolution, :Conflict, :keep_first],
    "Validation" => [:validate, :Issue],
    "Data quality" => [:audit, :AuditReport, :Finding, :AUDIT_CHECKS, :ID_PATTERNS, :findings, :passed,
                       :count_findings, :assert_quality, :QualityError],
    "Statistics" => [:graph_stats, :GraphStats, :stats_table, :write_stats],
    "Vocabulary" => [:Term, :term, :terms, :is_a, :is_term, :VOCABULARY],
    "Types and schema" => [:Resource, :Entity, :NodeEntity, :EdgeEntity, :Taxon, :Provenance, :Gene, :Dna, :Rna,
                           :Protein, :MolecularComplex, :SmallMolecule, :OrthologGroup, :Interaction, :Influence,
                           :Reaction, :PathwayModule, :class_name, :Prop, :schema, :assign!],
    "Any format" => [:load, :load!, :save, :formats],
    "RDF" => [:IRI, :Literal, :Triple, :triples, :from_triples, :expand, :compact,
              :write_turtle, :parse_turtle, :read_turtle, :write_ntriples, :parse_ntriples, :read_ntriples,
              :write_jsonld, :parse_jsonld, :read_jsonld, :write_rdfxml],
    "JSON and tables" => [:write_json, :read_json, :parse_json, :write_table, :read_table],
    "Networks" => [:Arc, :network, :write_sif, :read_sif, :write_graphml, :write_dot],
]

let exported = Set(filter(!=(:BioNExt), names(BioNExt))), listed = Set(vcat(last.(GROUPS)...))
    missing_ = setdiff(exported, listed)
    isempty(missing_) || error("exported but not in GROUPS: $(collect(missing_))")
end

open(joinpath(OUT, "api.md"), "w") do io
    print(io, HEADER)
    println(io, "# API reference\n\nEvery exported name, with its docstring. In the REPL, `?name` shows the same text.",
            " `Base.isvalid(kg)`, `Base.merge!(kg, other)` and `Base.delete!(kg, id)` are also extended for graphs.\n")
    for (group, syms) in GROUPS
        println(io, "- [$group](#", lowercase(replace(group, " " => "-")), ")")
    end
    for (group, syms) in GROUPS
        println(io, "\n## $group\n")
        for s in syms
            println(io, "### `", s, "`\n")
            d = docstring(getfield(BioNExt, s))
            # Docstrings start with an indented signature line; turn it into a code block.
            d = replace(d, r"^    (\S[^\n]*)\n"m => s"```julia\n\1\n```\n")
            println(io, d, "\n")
        end
    end
end

println("wrote ", join(readdir(OUT), ", "), " to ", OUT)
