# Regenerate src/vocabulary_data.jl from the BioNExt ontology (Turtle).
#
#   julia scripts/generate_vocabulary.jl [path/to/bne_ontology.ttl]
#
# Records the bn:/bnr: namespaces and owl:versionInfo, and extracts every controlled-vocabulary term (classes punned as owl:NamedIndividual)
# together with its label, comment, parent, seeAlso and expectedLeft/expectedRight.
# This is a block-based reader tailored to the rdflib-style layout of the ontology
# file, not a general Turtle parser.

const ROOT = dirname(@__DIR__)
ttl_path = isempty(ARGS) ? joinpath(ROOT, "ontology", "bne_ontology.ttl") : ARGS[1]
out_path = joinpath(ROOT, "src", "vocabulary_data.jl")

function curie_list(block, pred)
    m = match(Regex(pred * raw"\s+((?:(?:bn:\w+|<[^>]+>)\s*,?\s*)+)"), block)
    m === nothing && return String[]
    [String(x.match) for x in eachmatch(r"bn:\w+|<[^>]+>", m[1])]
end

strip_bn(s) = replace(s, "bn:" => "")
first_string(block, pred) =
    (m = match(Regex(pred * raw"\s+\"((?:[^\"\\\\]|\\\\.)*)\""), block)) === nothing ? "" : m[1]

ttl = read(ttl_path, String)
namespace(prefix) = (m = match(Regex("@prefix\\s+$prefix:\\s*<([^>]+)>"), ttl)) === nothing ?
    error("no @prefix $prefix: in $ttl_path") : m[1]
version = (m = match(r"owl:versionInfo\s+\"([^\"]+)\"", ttl)) === nothing ? "unknown" : m[1]

terms = []
for raw in split(ttl, r"\n\s*\n")
    block = replace(strip(raw), r"\s+" => " ")
    startswith(block, "bn:") || continue
    occursin("owl:NamedIndividual", block) || continue
    subj = strip_bn(split(block)[1])
    parents = curie_list(block, "rdfs:subClassOf")
    parent = isempty(parents) ? "" : strip_bn(parents[1])
    see = String[strip(s, ['<', '>']) for s in curie_list(block, "rdfs:seeAlso")]
    push!(terms, (id = subj,
                  label = first_string(block, "rdfs:label"),
                  comment = first_string(block, "rdfs:comment"),
                  parent = parent,
                  see_also = see,
                  left = strip_bn.(curie_list(block, "bn:expectedLeft")),
                  right = strip_bn.(curie_list(block, "bn:expectedRight"))))
end
sort!(terms; by = t -> t.id)

symlist(v) = "Symbol[" * join((":" * x for x in v), ", ") * "]"

open(out_path, "w") do io
    println(io, "# AUTO-GENERATED by scripts/generate_vocabulary.jl from bne_ontology.ttl — do not edit.")
    println(io, "const ONTOLOGY_VERSION = ", repr(version))
    println(io, "const BN = ", repr(namespace("bn")), "    # ontology namespace")
    println(io, "const BNR = ", repr(namespace("bnr")), "  # default resource namespace")
    println(io, "const VOCABULARY_DATA = [")
    for t in terms
        parent = isempty(t.parent) ? "nothing" : ":" * t.parent
        println(io, "    Term(:", t.id, ", ", repr(t.label), ", ", repr(t.comment), ", ", parent, ",")
        println(io, "         ", repr(t.see_also), ", ", symlist(t.left), ", ", symlist(t.right), "),")
    end
    println(io, "]")
end
println("wrote $(length(terms)) terms to $out_path")
